const base = process.env.PPP_URL ?? 'http://127.0.0.1:4173/pocket-pet-planet/';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
await p.goto(base + 'blank.html'); await p.evaluate(() => localStorage.clear());
await p.goto(base + '?time=17:40&weather=clear&date=2026-11-03');
await p.waitForFunction(() => window.__ppp?.ready);
const s = await p.evaluate(() => JSON.parse(localStorage.getItem('pocket-pet-planet:v1')));
const wear = [{ head: 'cometcap', neck: 'stardust' }, { head: 'moonhalo' }, { head: 'cometcap' }, { neck: 'stardust' }];
